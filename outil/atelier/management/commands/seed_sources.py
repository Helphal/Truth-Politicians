class Command(BaseCommand):
    help = "Enregistre le catalogue initial de sources officielles sans lancer le réseau."

    def handle(self, *args, **options):
        created = 0
        for item in SOURCES:
            defaults = dict(item)
            stable_id = defaults.pop("stable_id")
            existing = Source.objects.filter(stable_id=stable_id).first()
            if existing:
                # Le catalogue décrit la qualification candidate, mais ne doit
                # pas effacer un état opérationnel déjà observé par le collecteur.
                if existing.access_status in {
                    Source.AccessStatus.ACTIVE,
                    Source.AccessStatus.BLOCKED,
                    Source.AccessStatus.RETIRED,
                }:
                    defaults["access_status"] = existing.access_status
                elif existing.last_success_at:
                    defaults["access_status"] = Source.AccessStatus.ACTIVE
                defaults["qualified_at"] = existing.qualified_at or timezone.now()
                defaults["last_success_at"] = existing.last_success_at
                defaults["last_failure_at"] = existing.last_failure_at
                defaults["last_failure_code"] = existing.last_failure_code
            else:
                defaults["qualified_at"] = timezone.now()
            _, was_created = Source.objects.update_or_create(stable_id=stable_id, defaults=defaults)
            created += int(was_created)
        self.stdout.write(self.style.SUCCESS(f"sources={len(SOURCES)} created={created} network_calls=0"))
